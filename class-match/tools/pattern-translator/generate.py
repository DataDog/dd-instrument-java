#!/usr/bin/env python3
"""Generates DDTracePatterns.java from the recorder output and the DD_TRACE corpus source.

Usage: record.sh | generate.py <DDTraceClassMatcherGraphs.java> <out DDTracePatterns.java>
"""
import re, sys

src_path, out_path = sys.argv[1], sys.argv[2]
src = open(src_path).read()
rows = [l.rstrip('\n').split('\t') for l in sys.stdin if l.strip()]

def statement(orig):
    """Source text of the expression assigned to result[orig]."""
    m = re.search(r'result\[%d\] =' % orig, src)
    i, depth, in_str = m.end(), 0, False
    while True:
        c = src[i]
        if in_str:
            if c == '\\': i += 1
            elif c == '"': in_str = False
        elif c == '"': in_str = True
        elif c == '(': depth += 1
        elif c == ')': depth -= 1
        elif c == ';' and depth == 0:
            return ' '.join(src[m.end():i].split())
        i += 1

def group_key(orig):
    """Instrumentation source file of result[orig], from the location comment above it."""
    pos = re.search(r'result\[%d\] =' % orig, src).start()
    comments = re.findall(r'^\s*// (\S+\.java):\d+$', src[:pos], flags=re.M)
    return comments[-1]

imports = re.findall(r'^import .*;$', src, flags=re.M)
n = len(rows)
CHUNK = 100
out = []
out.append('package datadog.instrument.classmatch;\n')
out += imports
out.append('''
/**
 * DD_TRACE selectors as lazily-compiled member patterns, generated by
 * tools/pattern-translator from {@link DDTraceClassMatcherGraphs} (same order as its branches).
 * A {@code null} pattern entry means the selector uses the predicate fallback.
 */
final class DDTracePatterns {
  private DDTracePatterns() {}

  // Unlike method(), unconstrained Byte Buddy predicates also accept constructors.
  private static MethodMatcher anyMethod() {
    return m -> true;
  }

  private static FieldMatcher anyField() {
    return f -> true;
  }
''')
out.append('  static String[][] patterns() {')
out.append('    String[][] result = new String[%d][];' % n)
for c in range(0, n, CHUNK):
    out.append('    fill%d(result);' % c)
out.append('    return result;\n  }\n')
for c in range(0, n, CHUNK):
    out.append('  private static void fill%d(String[][] result) {' % c)
    for k in range(c, min(n, c + CHUNK)):
        row = rows[k]
        if row[1] == 'PATTERNS':
            lits = ', '.join('"%s"' % p for p in row[2:])
            out.append('    result[%d] = new String[] {%s};' % (k, lits))
    out.append('  }\n')
annotations = sorted({tok[1:] for r in rows if r[1] == 'PATTERNS' for p in r[2:] for tok in p.split(' ') if tok.startswith('@')})
out.append('  /** Annotations the patterns need extracted when parsing (known at build time). */')
out.append('  static String[] annotations() {')
out.append('    return new String[] {%s};' % ', '.join('"%s"' % a for a in annotations))
out.append('  }\n')
keys = [group_key(int(r[0])) for r in rows]
ids = {}
for k in keys:
    ids.setdefault(k, len(ids))
out.append('  /** Instrumentation group of each selector (selectors from the same source file). */')
out.append('  static int[] groups() {')
out.append('    return new int[] {%s};' % ', '.join(str(ids[k]) for k in keys))
out.append('  }\n')
out.append('  /** Predicate fallbacks, only for selectors patterns can\'t express. */')
out.append('  static ClassMatcher[] fallbacks() {')
out.append('    ClassMatcher[] result = new ClassMatcher[%d];' % n)
for k, row in enumerate(rows):
    if row[1] == 'FALLBACK':
        out.append('    result[%d] = %s;' % (k, statement(int(row[0]))))
out.append('    return result;\n  }\n}')
open(out_path, 'w').write('\n'.join(out) + '\n')
print('selectors=%d patterns=%d fallbacks=%d' % (
    n, sum(1 for r in rows if r[1] == 'PATTERNS'), sum(1 for r in rows if r[1] == 'FALLBACK')))
